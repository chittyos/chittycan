#!/usr/bin/env node
/**
 * Render a `can wip branches --remote --json` plan as the body of the branch
 * hygiene tracking issue.
 *
 * A separate file rather than an inline `node -e` in the workflow: embedded in
 * YAML this is unreachable by the test suite, and the only way to find out it
 * throws is a red cron run at 08:00 on a Monday.
 *
 * Usage: render-branch-plan.mjs <plan.json> <body.md> <count.txt>
 * Exits non-zero on malformed input — a rendering failure must not be
 * mistakable for "nothing to report".
 */
import { readFileSync, writeFileSync } from "node:fs";

const [planPath, bodyPath, countPath] = process.argv.slice(2);
if (!planPath || !bodyPath || !countPath) {
  console.error("usage: render-branch-plan.mjs <plan.json> <body.md> <count.txt>");
  process.exit(2);
}

const plan = JSON.parse(readFileSync(planPath, "utf8"));
if (!Array.isArray(plan.actions)) {
  console.error("plan.json has no actions array — refusing to render an empty report");
  process.exit(2);
}

// Validate every action, not just the array wrapper. An action missing `sha`
// or `branch` would otherwise render `git push origin --delete undefined` into
// a command block a maintainer is invited to paste.
const acts = plan.actions;
for (const [i, a] of acts.entries()) {
  const bad =
    !a || typeof a !== "object"
      ? "not an object"
      : typeof a.branch !== "string" || !a.branch
        ? "missing branch"
        : typeof a.sha !== "string"
          ? "missing sha"
          : a.refused != null && typeof a.refused !== "string"
            ? "non-string refused"
            : null;
  if (bad) {
    console.error(`plan.actions[${i}]: ${bad} — refusing to render`);
    process.exit(2);
  }
}

/**
 * POSIX single-quote a branch name for a copy-pasteable shell command.
 *
 * git permits `$`, `;`, backticks and newlines in ref names, so an unquoted
 * `git push origin --delete ${a.branch}` in the issue body is remote code
 * execution against whoever pastes it: anyone able to push a branch to origin
 * chooses the text. Single quotes disable every expansion; the only character
 * needing care inside them is the single quote itself.
 */
const shq = (s) => `'${String(s).replaceAll("'", `'\\''`)}'`;
// Classified by ELIGIBILITY, not by whether a write happened. On a dry run
// nothing has `archivedAs`, and filtering on it emptied every section — a
// report that read as "no branch qualifies" when the truth was "nothing was
// written yet".
const proposed = acts.filter((a) => a.proposedDelete && !a.refused);
const archived = acts.filter((a) => !a.proposedDelete && !a.refused);
const refused = acts.filter((a) => a.refused);

const row = (a) =>
  `| \`${a.branch}\` | \`${(a.sha || "").slice(0, 8) || "—"}\` | ${a.refused ?? a.archivedAs ?? "—"} |`;
const table = (head, xs) => `| branch | tip | ${head} |\n|---|---|---|\n${xs.map(row).join("\n")}\n\n`;

let body = "";
if (plan.dryRun) body += "> Dry run — no archive refs were written.\n\n";
body +=
  `**${proposed.length}** ${proposed.length === 1 ? "branch holds" : "branches hold"} nothing ` +
  "the default branch does not already have. Every tip below is archived, so " +
  "deleting is reversible.\n\n";

if (proposed.length) {
  body += "## Proposed for deletion\n\n" + table("archived as", proposed);
  // Leased to the archived sha. Between this run and the moment a human pastes
  // the command, the branch can receive new commits that the archive does not
  // contain — a bare `--delete` would destroy them and the "nothing is lost"
  // guarantee with them. With the lease, a moved branch makes the delete fail
  // instead, and the next run re-archives the newer tip.
  body +=
    "```sh\n" +
    proposed
      .map((a) => `git push origin --force-with-lease=${shq(a.branch)}:${a.sha} --delete ${shq(a.branch)}`)
      .join("\n") +
    "\n```\n\n";
}
if (archived.length) {
  body +=
    (plan.dryRun
      ? "## Would archive (still unlandable, never deleted)\n\n"
      : "## Archived only (still unlandable, not deleted)\n\n") + table("archived as", archived);
}
if (refused.length) {
  body += "## Left alone\n\n" + table("reason", refused);
}

body += `**Undo any of this:**\n\n\`\`\`sh\n${plan.reversal ?? "(no reversal reported)"}\n\`\`\`\n`;
if (process.env.RUN_URL) {
  body += `\n<sub>Generated by \`.github/workflows/branch-hygiene.yml\` — run ${process.env.RUN_URL}</sub>\n`;
}

writeFileSync(bodyPath, body);
// Refusals deliberately count: a branch the job declined to touch is something
// a human still needs to see, and a run that only produced refusals must not
// report "nothing to do" and stay silent.
writeFileSync(countPath, String(proposed.length + archived.length + refused.length));
